               'blankIdx', 'none (RULING 2026-10-12 (a): masked spans as NaN only)', ...
               'spanRule', struct( ...
                   'name', 'sw_span_rule_20261012_v2', ...
                   'exclusionSec', 10, 'pairZoneSec', 15, 'pairMinSec', 7, ...
                   'exclusionFromCleanTime', true, ...
                   'ruling', ['RULING 2026-10-12 (Andrea), v2: (a) C1 extent, masked spans ' ...
                              'as NaN only, no 15 s buffer around them (file start/end ' ...
                              'handling unchanged); (b) ignore a peak inside a masked span ' ...
                              'or < 10 s from its edge (8.17 s low-pass settling + 2.5 s ' ...
                              'smoothing half-window, rounded), and leave that time out of ' ...
                              'the rate''s clean time; (c) drop BOTH of two consecutive ' ...
                              'detected peaks < 7 s apart when both lie within 15 s of a ' ...
                              'masked span''s edge (union of the spans'' zones, either ' ...
                              'side); (d) rate and timing from kept peaks only, drops by (b) ' ...
                              'and (c) recorded per epoch'], ...
                   'distance', ['seconds from the peak''s epoch row to the nearest masked ' ...
                                'row of a span (0 inside): (first row - peak) / fs before a ' ...
                                'span, (peak - last row) / fs after it'], ...
                   'consecutive', ['consecutive in her detected list (her peaks after her own ' ...
                                   'invalid / file-edge rejection), before (b) is applied ' ...
                                   '(Andrea 2026-10-12)'], ...
                   'zone_union', ['the 15 s zone is the union over every masked span; a pair ' ...
                                  'whose peaks are near two different spans counts (Andrea ' ...
                                  '2026-10-12)'], ...

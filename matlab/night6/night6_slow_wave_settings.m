                   'source', ['Andrea 2026-10-12: kept peaks within 25 s before a span start, ' ...
                              '> 2 x the channel''s median kept-peak amplitude; DIAGNOSTIC, ' ...
                              'no rate depends on it (night6_slow_wave_pre_span_peaks)']), ...
               'source', ['batch_process.m P.sw_* (= T / tolerance_sweep); NOT ' ...
                          'run_continuous.m (lowPassOn false, 2 Hz, order 4, window 10, buffer 3)']);
end

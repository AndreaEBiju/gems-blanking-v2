function W = night6_slow_wave_settings()
% NIGHT6_SLOW_WAVE_SETTINGS  The slowWaveAnalysis_new settings Night 6 runs with. ONE site.
%
%   W = night6_slow_wave_settings()
%
% RULING 2026-10-09 (h) 1: Night 6's slow-wave rate and timing keep batch_process.m's P.sw_*
% (= T / tolerance_sweep) - low-pass on, 0.15 Hz, order 2, 5 s smoothing, 15 s edge buffer;
% NOT run_continuous.m (lowPassOn false, 2 Hz, order 4, window 10, buffer 3). The record's
% params().slow_wave, the arguments night6_call_slow_wave hands her function and the caveat
% text in every slow-wave output's provenance (night6_slow_wave_caveats) are all built from
% this one struct (invariant 33), so they cannot disagree.
%
% RULING 2026-10-12 (Andrea; replaces RULING 2026-10-09 (c) 6 for slow wave; PILOT - Andrea
% decides before slow wave runs on everything):
%   (a) masked spans go in as NaN ONLY, never as blankIdx, so her edgeBufferSec guards the
%       file's own start and end (15 s, unchanged) and NO masked span (0 s around spans);
%   (b) after detection, a peak inside a masked span or less than spanRule.exclusionSec
%       (5 s) from a masked-span edge is ignored;
%   (c) two consecutive peaks less than spanRule.pairMinSec (7 s) apart are BOTH dropped
%       when both lie within spanRule.pairZoneSec (15 s) of a masked span's edge, on either
%       side; elsewhere close peaks are kept as her analysis finds them;
%   (d) rate and timing outputs use only the kept peaks; per epoch the peaks dropped by (b)
%       and by (c) are recorded (night6_slow_wave_span_rule, night6_call_slow_wave).
% The rule is NOT covered by the harm test (which measured the (c) 6 configuration); every
% output says so (spanRule.harm_test).
    W = struct('lowPassOn', true, 'lowPassCutoff', 0.15, 'lowPassOrder', 2, ...
               'smoothWindow', 5, 'edgeBufferSec', 15, ...
               'edgeBufferScope', ['the file''s own start and end only: masked spans are ' ...
                                   'passed as NaN only, blankIdx = [] (RULING 2026-10-12 (a))'], ...
               'blankIdx', 'none (RULING 2026-10-12 (a): masked spans as NaN only)', ...
               'spanRule', struct( ...
                   'name', 'sw_span_rule_20261012', ...
                   'exclusionSec', 5, 'pairZoneSec', 15, 'pairMinSec', 7, ...
                   'ruling', ['RULING 2026-10-12 (Andrea): (a) C1 extent, masked spans as ' ...
                              'NaN only, no 15 s buffer around them (file start/end ' ...
                              'handling unchanged); (b) ignore a peak inside a masked span ' ...
                              'or < 5 s from its edge; (c) drop BOTH of two consecutive ' ...
                              'peaks < 7 s apart only when both lie within 15 s of a ' ...
                              'masked span''s edge, either side; (d) rate and timing from ' ...
                              'kept peaks only, drops by (b) and (c) recorded per epoch'], ...
                   'distance', ['seconds from the peak''s epoch row to the nearest masked ' ...
                                'row of a span (0 inside): (first row - peak) / fs before a ' ...
                                'span, (peak - last row) / fs after it'], ...
                   'consecutive', ['consecutive in her detected list (her peaks after her own ' ...
                                   'invalid / file-edge rejection), before (b) is applied'], ...
                   'harm_test', ['NOT covered by the harm test: the harm test measured ' ...
                                 'blankIdx with a 15 s edge buffer at every masked span ' ...
                                 '(RULING 2026-10-09 (c) 6), not this rule'], ...
                   'pilot', true), ...
               'source', ['batch_process.m P.sw_* (= T / tolerance_sweep); NOT ' ...
                          'run_continuous.m (lowPassOn false, 2 Hz, order 4, window 10, buffer 3)']);

%   (b) after detection, a peak inside a masked span or less than spanRule.exclusionSec
%       (10 s = the measured 8.17 s low-pass settling + the 2.5 s smoothing half-window,
%       rounded) from a masked-span edge is ignored, AND the time inside those zones is left
%       out of the clean time her rate pools (so the rate is not biased low);
%   (c) two consecutive peaks of her DETECTED list (before (b)) less than
%       spanRule.pairMinSec (7 s) apart are BOTH dropped when both lie within
